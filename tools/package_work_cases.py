def main():
    files = sorted(SOURCE.glob("*.png"), key=lambda p: p.stat().st_mtime)
    entries = anchors + followups
    if len(files) != 50 or len(entries) != 50:
        raise RuntimeError(f"Expected 50 files/entries, found {len(files)}/{len(entries)}")
    OUTPUT.mkdir(parents=True, exist_ok=True)
    rows = []
    for source, (folder, stage, description) in zip(files, entries):
        target_dir = OUTPUT / folder
        target_dir.mkdir(exist_ok=True)
        target = target_dir / f"{folder}_{stage}.webp"
        with Image.open(source) as image:
            image.convert("RGB").save(target, "WEBP", quality=88, method=6)
        rows.append([folder, stage, description, str(target.relative_to(OUTPUT)), target.stat().st_size])
    with (OUTPUT / "작업사례_목록.csv").open("w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerow(["키워드", "장면", "스토리 설명", "파일", "용량(bytes)"])
        writer.writerows(rows)
    readme = """작업사례 이미지 50장 (WEBP)\n\n각 폴더는 하나의 작업 스토리입니다. 파일명 번호 순서대로 사용하세요.\n구성: 문제 확인/진단 → 작업 진행 → 시험 또는 복구 완료\n이미지는 AI로 생성된 홍보용 예시 이미지이며, 실제 고객 현장 촬영본으로 표시해서는 안 됩니다.\n로고, 업체명, 워터마크, 연락처 문구는 포함하지 않았습니다.\n"""
    (OUTPUT / "README.txt").write_text(readme, encoding="utf-8")
    shutil.make_archive(str(OUTPUT), "zip", OUTPUT.parent, OUTPUT.name)
    print(f"webp_count={len(list(OUTPUT.rglob('*.webp')))}")
    print(f"output={OUTPUT}")
    print(f"zip={OUTPUT}.zip")

if __name__ == "__main__":
    main()
