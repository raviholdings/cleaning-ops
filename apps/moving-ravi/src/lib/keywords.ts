export function subKeywordsFor(main: string): string[] {
  const own = KEYWORD_GROUPS[main] ?? [];
  const borrowed = BORROWED_SUBS[main] ?? [];
  // 자기 것을 먼저 쓰고 모자란 만큼만 빌린다. 최소 3개는 되게 한다.
  if (own.length >= 3) return own;
  return [...own, ...borrowed.filter((w) => !own.includes(w))];
}
